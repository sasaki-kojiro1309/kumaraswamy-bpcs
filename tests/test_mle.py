def make_block(label, times, causes, removals=None):
    removals = (0,)*len(times) if removals is None else removals
    scheme = BlockScheme(label, len(times)+sum(removals), len(times), removals)
    return BlockData(scheme, tuple(Observation(label, t, c, r)
                                  for t, c, r in zip(times, causes, removals)))


def quantile_fixture(a, sizes=(600, 500)):
    """Deterministic population-quantile grid, not random or censored simulation."""
    blocks = []
    for label, n, b1, b2, period, cause1 in [
        ("A", sizes[0], 1., 2., 3, 1), ("B", sizes[1], .8, 1.2, 5, 2)
    ]:
        p = (np.arange(n)+.5)/n
        times = np.exp(np.log(-np.expm1(np.log1p(-p)/(b1+b2)))/a)
        causes = [1 if j % period < cause1 else 2 for j in range(n)]
        blocks.append(make_block(label, times, causes))
    return BPCSExperiment(tuple(blocks))


@pytest.mark.parametrize("a,pairs", [
    (.5, {"A": (.4, 1.2), "B": (1., .3)}),
    (2., {"A": (1., 2.), "B": (.8, 1.2)}),
    (5., {"A": (2., .3), "B": (.2, 3.)}),
])
def test_scores_against_independent_finite_differences_of_stage3(a, pairs):
    data = load_example()
    actual = score(data, a, pairs)
    h = a*1e-5
    numerical = (loglikelihood(data, a+h, pairs)-loglikelihood(data, a-h, pairs))/(2*h)
    assert actual["a"] == pytest.approx(numerical, rel=2e-7, abs=1e-8)
    for label, pair in pairs.items():
        for c, value in enumerate(pair):
            h = value*1e-5
            upper, lower = dict(pairs), dict(pairs)
            upper[label] = tuple(v+h if j == c else v for j, v in enumerate(pair))
            lower[label] = tuple(v-h if j == c else v for j, v in enumerate(pair))
            derivative = (loglikelihood(data, a, upper)-loglikelihood(data, a, lower))/(2*h)
            assert actual["b_by_block"][label][c] == pytest.approx(derivative, rel=2e-7, abs=1e-8)


@pytest.mark.parametrize("a", [.3, 1., 4.])
def test_conditional_estimates_match_independent_inner_optimization(a):
    data = load_example()
    conditional = conditional_estimates(data, a)
    def objective(v):
        values = np.exp(v)
        return -loglikelihood(data, a, {"A": tuple(values[:2]), "B": tuple(values[2:])})
    direct = minimize(objective, np.zeros(4), method="BFGS", options={"gtol": 1e-6})
    expected = [*conditional["A"], *conditional["B"]]
    assert_allclose(np.exp(direct.x), expected, rtol=2e-5)
    assert profile_loglikelihood(data, a) == pytest.approx(-direct.fun, abs=1e-10)
    assert profile_loglikelihood(data, a) == pytest.approx(loglikelihood(data, a, conditional))
    assert (profile_loglikelihood(data, a)-profile_loglikelihood(data, a, include_constant=False)
            == pytest.approx(log_censoring_constant(data)))


@pytest.mark.parametrize("a", [.05, .5, 2., 20.])
def test_profile_score_matches_profile_difference_and_envelope_score(a):
    data = load_example()
    h = a*1e-5
    derivative = (profile_loglikelihood(data, a+h)-profile_loglikelihood(data, a-h))/(2*h)
    assert profile_score(data, a) == pytest.approx(derivative, rel=2e-6, abs=1e-7)
    assert profile_score(data, a) == pytest.approx(score(data, a, conditional_estimates(data, a))["a"], abs=1e-10)


def test_teaching_profile_and_independent_direct_joint_fit_agree():
    data = load_example()
    primary, direct = fit_mle(data), fit_direct(data)
    assert primary.converged and direct.converged
    assert primary.status == direct.status == "interior_mle"
    assert direct.a == pytest.approx(primary.a, rel=1e-6)
    for label in primary.b_by_block:
        assert_allclose(direct.b_by_block[label], primary.b_by_block[label], rtol=1e-6)
    assert direct.loglikelihood == pytest.approx(primary.loglikelihood, abs=1e-10)
    assert primary.loglikelihood == pytest.approx(loglikelihood(data, primary.a, primary.b_by_block))
    assert primary.loglikelihood > loglikelihood(data, 2., {"A": (1., 2.), "B": (.8, 1.2)})
    assert abs(score(data, primary.a, primary.b_by_block)["a"]) < 1e-8
    for label, pair in primary.b_by_block.items():
        counts = next(b.cause_counts for b in data.blocks if b.scheme.block == label)
        assert pair[0]/sum(pair) == pytest.approx(counts[1]/sum(counts.values()))
    assert len(direct.diagnostics["starts"]) == 4
    assert primary.diagnostics["log_parameter_score_norm"] < primary.diagnostics["score_threshold"]
    assert abs(primary.diagnostics["profile_minus_joint_loglikelihood"]) < 1e-10


