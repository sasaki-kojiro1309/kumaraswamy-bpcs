@pytest.mark.parametrize("k", [1, 3])
def test_fits_support_arbitrary_number_and_order_of_blocks(k):
    template = load_example().blocks[0]
    blocks = [make_block(f"facility_{j}", tuple(r.time for r in template.observations),
                         tuple(r.cause for r in template.observations), template.scheme.withdrawals)
              for j in range(k)]
    data = BPCSExperiment(tuple(reversed(blocks)))
    fit = fit_mle(data)
    direct = fit_direct(data)
    reference = fit_mle(BPCSExperiment((template,)))
    assert fit.converged and direct.converged
    assert fit.a == pytest.approx(reference.a, rel=1e-9)
    assert direct.a == pytest.approx(fit.a, rel=2e-6)
    for pair in fit.b_by_block.values():
        assert_allclose(pair, reference.b_by_block["A"], rtol=1e-9)
