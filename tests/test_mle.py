def boundary_fixture():
    return BPCSExperiment((
        make_block("A", (.15, .4, .7), (1, 1, 1), (1, 0, 2)),
        make_block("B", (.1, .25, .55, .8), (2, 1, 2, 2), (0, 1, 0, 2)),
    ))


def test_zero_count_is_a_boundary_supremum_not_a_tiny_positive_mle():
    data = boundary_fixture()
    result, direct = fit_mle(data), fit_direct(data)
    assert result.converged and direct.converged
    assert result.status == direct.status == "boundary_supremum"
    assert result.b_by_block["A"][1] == direct.b_by_block["A"][1] == 0.0
    assert result.diagnostics["boundary_parameters"] == (("A", 2),)
    assert result.diagnostics["boundary_one_sided_scores"]["A"][2] < 0
    assert direct.a == pytest.approx(result.a, rel=2e-6)
    assert direct.loglikelihood == pytest.approx(result.loglikelihood, abs=1e-9)
    # Times and total failure counts unchanged: profile a is unchanged by marks.
    assert result.a == pytest.approx(fit_mle(load_example()).a)
    assert result.b_by_block["A"][0] == pytest.approx(sum(fit_mle(load_example()).b_by_block["A"]))
    for eps in (1e-3, 1e-6):
        interior = dict(result.b_by_block)
        interior["A"] = (interior["A"][0], eps)
        W = 3/result.b_by_block["A"][0]
        assert result.loglikelihood-loglikelihood(data, result.a, interior) == pytest.approx(eps*W, abs=1e-12)
        assert score(data, result.a, interior)["b_by_block"]["A"][1] == pytest.approx(-W)


def test_single_failure_block_is_allowed_if_another_block_identifies_a():
    data = BPCSExperiment((boundary_fixture().blocks[0], make_block("B", (.3,), (2,), (4,))))
    result = fit_mle(data)
    assert result.converged and result.status == "boundary_supremum"
    assert result.b_by_block["B"][0] == 0


def test_all_single_failure_blocks_have_unbounded_likelihood():
    data = BPCSExperiment((make_block("A", (.3,), (1,), (4,)), make_block("B", (.6,), (2,), (2,))))
    assert profile_loglikelihood(data, 100) > profile_loglikelihood(data, 10)
    for fit in (fit_mle, fit_direct):
        result = fit(data)
        assert not result.converged
        assert result.status == "unbounded_likelihood"
        assert result.a is None and not result.b_by_block
        assert result.loglikelihood == np.inf


def test_profile_strict_concavity_and_root_signs_numerically():
    data = load_example()
